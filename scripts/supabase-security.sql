-- Run this in the Supabase SQL editor.
-- This script creates/updates the tables and RLS rules used by the Netlify-hosted app.

create extension if not exists pgcrypto;

create table if not exists public.prices (
  id bigint generated by default as identity primary key,
  cloth_type text not null,
  ironing_price numeric not null check (ironing_price >= 0),
  washing_price numeric not null check (washing_price >= 0),
  gender text not null check (gender in ('Male', 'Female')),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 80),
  email text not null check (char_length(email) <= 120),
  message text not null check (char_length(message) <= 2000),
  created_at timestamptz not null default now()
);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text,
  email text not null unique,
  role text not null default 'user' check (role in ('admin', 'user')),
  created_via text,
  invited_by uuid,
  created_at timestamptz not null default now()
);

alter table public.users add column if not exists created_via text;
alter table public.users add column if not exists invited_by uuid;
alter table public.users add column if not exists created_at timestamptz not null default now();

create table if not exists public.admin_otp_requests (
  id uuid primary key default gen_random_uuid(),
  candidate_email text not null,
  otp_hash text not null,
  otp_salt text not null,
  invited_by uuid not null,
  attempts integer not null default 0,
  max_attempts integer not null default 5,
  expires_at timestamptz not null,
  used_at timestamptz,
  invalidated_at timestamptz,
  requested_ip text,
  created_at timestamptz not null default now(),
  constraint admin_otp_attempts_check check (attempts <= max_attempts),
  constraint admin_otp_expiry_after_creation check (expires_at > created_at)
);

create index if not exists admin_otp_requests_candidate_email_idx
  on public.admin_otp_requests (candidate_email);

create index if not exists admin_otp_requests_pending_idx
  on public.admin_otp_requests (candidate_email, created_at desc)
  where used_at is null and invalidated_at is null;

create table if not exists public.admin_invite_audit (
  id bigint generated by default as identity primary key,
  event_type text not null,
  candidate_email text,
  inviting_admin_id uuid,
  ip_address text,
  outcome_detail text,
  created_at timestamptz not null default now()
);

create index if not exists admin_invite_audit_candidate_email_idx
  on public.admin_invite_audit (candidate_email, created_at desc);

create index if not exists admin_invite_audit_ip_idx
  on public.admin_invite_audit (ip_address, created_at desc);

create table if not exists public.contact_rate_limits (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists contact_rate_limits_ip_created_idx
  on public.contact_rate_limits (ip_hash, created_at desc);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.users
    where lower(email) = lower(auth.email())
      and role = 'admin'
  );
$$;

