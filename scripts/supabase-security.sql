-- Prices: public read, admin write.
drop policy if exists "prices public read" on public.prices;
create policy "prices public read"
on public.prices
for select
to anon, authenticated
using (true);

drop policy if exists "prices admin insert" on public.prices;
create policy "prices admin insert"
on public.prices
for insert
to authenticated
with check (public.is_admin());

drop policy if exists "prices admin update" on public.prices;
create policy "prices admin update"
on public.prices
for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "prices admin delete" on public.prices;
create policy "prices admin delete"
on public.prices
for delete
to authenticated
using (public.is_admin());

-- Messages: public insert, admin read/delete. No update policy.
drop policy if exists "messages anon insert" on public.messages;
create policy "messages anon insert"
on public.messages
for insert
to anon, authenticated
with check (true);

drop policy if exists "messages admin read" on public.messages;
create policy "messages admin read"
on public.messages
for select
to authenticated
using (public.is_admin());

drop policy if exists "messages admin delete" on public.messages;
create policy "messages admin delete"
on public.messages
for delete
to authenticated
using (public.is_admin());

-- Users: read own profile or admin-read. No browser insert/update/delete policies.
drop policy if exists "users own profile read" on public.users;
create policy "users own profile read"
on public.users
for select
to authenticated
using (lower(email) = lower(auth.email()) or public.is_admin());

-- OTP and rate-limit internals: service-role only through Netlify edge functions.
-- RLS is enabled and no anon/authenticated policies are created for these tables.
drop policy if exists "admin audit admin read" on public.admin_invite_audit;
create policy "admin audit admin read"
on public.admin_invite_audit

for select
to authenticated
using (public.is_admin());

-- In-store operations: customers, walk-in orders, settings, FAQs, and audit logs.
create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  phone text not null unique,
  email text,
  address text,
  notes text,
  total_orders integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  ticket_number text not null unique,
  customer_id uuid not null references public.customers(id) on delete restrict,
  status text not null default 'received' check (status in ('received', 'washing', 'ironing', 'packaging', 'ready', 'collected', 'cancelled')),
  subtotal numeric not null default 0 check (subtotal >= 0),
  discount numeric not null default 0 check (discount >= 0),
  total numeric not null default 0 check (total >= 0),
  amount_paid numeric not null default 0 check (amount_paid >= 0),
  payment_status text not null default 'unpaid' check (payment_status in ('unpaid', 'partial', 'paid')),
  expected_collection_at timestamptz,
  ready_at timestamptz,
  collected_at timestamptz,
  collected_by bigint references public.users(id),
  notes text,
  created_by bigint references public.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  price_id bigint references public.prices(id) on delete set null,
  item_name text not null,
  service_type text not null check (service_type in ('washing', 'ironing')),
  quantity integer not null check (quantity > 0),
  unit_price numeric not null check (unit_price >= 0),
  line_total numeric not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.business_settings (
  key text primary key,
  value text not null,
  updated_by bigint references public.users(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.faqs (
  id bigint generated by default as identity primary key,
  question text not null,
  answer text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  admin_id bigint references public.users(id),
  admin_email text,
  action text not null,
  entity_type text,
  entity_id text,
  old_value jsonb,
  new_value jsonb,
  created_at timestamptz not null default now()
);

create index if not exists customers_phone_idx on public.customers (phone);
create index if not exists orders_ticket_number_idx on public.orders (ticket_number);
create index if not exists orders_customer_created_idx on public.orders (customer_id, created_at desc);
