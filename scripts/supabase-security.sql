create or replace function public.increment_customer_order_count()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.customers
  set total_orders = total_orders + 1,
      updated_at = now()
  where id = new.customer_id;
  return new;
end;
$$;

drop trigger if exists orders_increment_customer_count on public.orders;
create trigger orders_increment_customer_count
after insert on public.orders
for each row execute function public.increment_customer_order_count();

